<script>
    (function() {
      const BASE_STAY_PRICE = 28750;
      let activeExtras = {
        'maybach': { name: 'VIP Mercedes Maybach Şoför', price: 3800 },
        'degustation': { name: 'Mum Işığında Uçurum Kenarı Tadımı', price: 9800 }
      };

      function formatLira(num) {
        return '\u20BA ' + num.toLocaleString('en-US');
      }

      function updateFolio() {
        const listContainer = document.getElementById('dynamic-extras-list');
        const emptyNotice = document.getElementById('no-extras-notice');
        const badge = document.getElementById('extras-count-badge');
        const subtotalEl = document.getElementById('subtotal-val');
        const totalEl = document.getElementById('total-val');

        listContainer.innerHTML = '';
        const keys = Object.keys(activeExtras);
        let extrasTotal = 0;

        if (keys.length === 0) {
          emptyNotice.classList.remove('hidden');
          badge.textContent = '0 Seçildi';
        } else {
          emptyNotice.classList.add('hidden');
          badge.textContent = keys.length + ' Seçildi';

          keys.forEach(key => {
            const item = activeExtras[key];
            extrasTotal += item.price;

            const div = document.createElement('div');
            div.id = 'item-' + key;
            div.className = 'flex items-start justify-between gap-3 text-sm animate-fadeIn';
            div.innerHTML = `
              <div class="flex flex-col">
                <span class="font-body-sm text-body-sm text-on-surface font-medium">${item.name}</span>
                <span class="font-label-sm text-label-sm text-on-surface-variant">Özel Eklenti</span>
              </div>
              <div class="flex items-center gap-2.5 flex-shrink-0">
                <span class="font-body-sm text-body-sm text-on-surface font-semibold">+${formatLira(item.price)}</span>
                <button onclick="removeExtra('${key}', ${item.price})" class="text-outline hover:text-error transition-colors p-1" title="Kaldır">
                  <span class="material-symbols-outlined text-[16px]">close</span>
                </button>
              </div>
            `;
            listContainer.appendChild(div);
          });
        }

        const grandTotal = BASE_STAY_PRICE + extrasTotal;
        subtotalEl.textContent = formatLira(grandTotal);
        totalEl.textContent = formatLira(grandTotal);
      }

      window.toggleExtra = function(button, id, name, price) {
        if (activeExtras[id]) {
          // Remove
          delete activeExtras[id];
          button.classList.remove('bg-secondary', 'text-on-secondary');
          button.classList.add('bg-primary', 'text-on-primary');
          button.innerHTML = '<span class="material-symbols-outlined text-[16px]">add</span><span>Konaklamaya Ekle</span>';
        } else {
          // Add
          activeExtras[id] = { name: name, price: price };
          button.classList.remove('bg-primary', 'text-on-primary');
          button.classList.add('bg-secondary', 'text-on-secondary');
          button.innerHTML = '<span class="material-symbols-outlined text-[16px]">check</span><span>✓ Eklendi</span>';
        }
        updateFolio();
      };

      window.removeExtra = function(id, price) {
        if (activeExtras[id]) {
          delete activeExtras[id];
          // Find button matching this extra
          const allButtons = document.querySelectorAll('.extra-btn');
          allButtons.forEach(btn => {
            const attr = btn.getAttribute('onclick');
            if (attr && attr.includes("'" + id + "'")) {
              btn.classList.remove('bg-secondary', 'text-on-secondary');
              btn.classList.add('bg-primary', 'text-on-primary');
              btn.innerHTML = '<span class="material-symbols-outlined text-[16px]">add</span><span>Konaklamaya Ekle</span>';
            }
          });
          updateFolio();
        }
      };

      // Initial Sync
      updateFolio();
    })();
</script>
@endpush
